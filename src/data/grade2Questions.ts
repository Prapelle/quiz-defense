const DIFFICULTY_CODES: Record<Difficulty, string> = { 'ง่าย': 'e', 'ปานกลาง': 'm', 'ยาก': 'h' };

/** Rotate the correct answer through positions A–D so it is not always in the same place. */
function build(): QuizQuestion[] {
  const questions: QuizQuestion[] = [];
  let n = 0;
  for (const subject of Object.keys(BANK) as Subject[]) {
    for (const difficulty of Object.keys(BANK[subject]) as Difficulty[]) {
      BANK[subject][difficulty].forEach(([question, correct, wrong, explanation], i) => {
        const answerIndex = ((n * 3 + 1) % 4) as 0 | 1 | 2 | 3;
        const choices = [...wrong];
        choices.splice(answerIndex, 0, correct);
        questions.push({
          id: `g2-${SUBJECT_CODES[subject]}-${DIFFICULTY_CODES[difficulty]}${i + 1}`,
          setId: GRADE2_SET_ID, question, choices: choices as QuizQuestion['choices'], answerIndex,
          explanation, subject, grade: 'ป.2', difficulty,
        });
        n += 1;
      });
    }
  }
  return questions;
}

